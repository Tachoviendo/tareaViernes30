CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(30) UNIQUE NOT NULL,
    nombres TEXT NOT NULL,
    apellidos TEXT NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    nombre_completo TEXT GENERATED ALWAYS AS (
        nombres || ' ' || apellidos
    ) STORED,
    grupos TEXT[] NOT NULL DEFAULT ARRAY['user']::TEXT[] CHECK (
        grupos <@ ARRAY['user', 'admin','superadmin']::TEXT[] 
        AND cardinality(grupos) > 0
    ),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS credenciales (
    id_usuario INTEGER PRIMARY KEY REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    password_hash TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS tareas (
    id_tarea INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_creador INTEGER NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    grupo TEXT NOT NULL CHECK (grupo IN ('user', 'admin', 'superadmin')),
    titulo VARCHAR(100) NOT NULL,
    descripcion TEXT,
    prioridad VARCHAR(10) NOT NULL DEFAULT '1:media' CHECK (prioridad IN ('0:baja', '1:media', '2:alta')),
    creada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    terminada TIMESTAMPTZ,
    estado TEXT GENERATED ALWAYS AS (
        CASE 
            WHEN terminada IS NOT NULL THEN 'Cerrada' 
            ELSE 'Abierta' 
        END
    ) STORED
);

